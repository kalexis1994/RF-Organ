#[cfg(test)]
mod tests {
    use super::*;

    /// Both tables are complete and physical: a wheel delivers something, and
    /// a wire passes a share of it. That the values are the readings' is held
    /// in the laboratory, which can reach the data they come from.
    #[test]
    fn the_tables_are_complete_and_physical() {
        assert!(TAPER.iter().all(|level| level.is_finite() && *level > 0.0));
        assert!(
            KEY_TAPER
                .iter()
                .flatten()
                .all(|gain| gain.is_finite() && *gain > 0.0)
        );
    }
}
