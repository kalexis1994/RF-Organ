//! What reaches the busbars of each wheel, and what each key lets through.
//!
//! A tone wheel's output does not reach the busbars at whatever level its
//! pickup happens to give it. The service manual describes what stands in the
//! way: "there are filters consisting of small transformers and condensers
//! associated with certain frequencies", each with "a single tapped winding"
//! whose tap is grounded, so that the side "connected to the corresponding
//! magnet coil through a condenser, forms a resonant circuit for the
//! fundamental frequency of that coil", which "tends to emphasize the
//! fundamental and suppress harmonics". And every contact a key closes reaches
//! its wheel through a tapering wire of its own resistance.
//!
//! The busbars sit on matching-transformer taps of a fraction of an ohm, so a
//! wheel delivers a current into them: V / Z straight onto a busbar, V / (Z +
//! R) through a wire of R ohms, Z being the impedance the wheel's coil, shunt
//! and filter present. That gives two tables.
//!
//! `TAPER` is each wheel's V / Z: fitted by `rf-organ-lab wheel-levels` so
//! that the engine, each wheel straight off a busbar, reproduces the median of
//! Hammond's B-3 Table V and six consoles read that way, with the console's own
//! response measured and taken out. `KEY_TAPER` is Z / (Z + R) for every key
//! and drawbar, from the tapering wires of five measured manuals and the
//! impedance three consoles show when the same wheel is read open-circuit,
//! onto a busbar and through a key. Both tables are scaled to keep a level the
//! stages after them were set by: the pedals' 16' fundamentals, which have no
//! key taper, and an 888 registration across the keyboard.
//!
//! Neither table is fitted to the readings taken through the keys - Hammond's
//! second chart and six consoles - and those are the check: played through
//! the key and drawbar each reading was taken on, the engine lands 2.2 dB rms
//! from their median, where it stood 4.5 dB away with every wheel and contact
//! at unity. The source data, the derivation and that check are in the
//! laboratory; see `docs/ARCHITECTURE.md` and `THIRD_PARTY_NOTICES.md`.

